#!/usr/bin/env python3
"""Build site/staff/app.js — the browser-only demo — as ONE classic script.

Why not ES modules: a module that fails to load fails silently. The button simply
stops working, with nothing on screen to say why, which is exactly how this was
reported three times. A single classic script has no import graph to break, runs in
anything, and is one cache entry rather than three.

Source of truth stays in portal/: the pricing engine is copied, never retyped, so the
demo cannot drift from what the real system computes.

    python portal/scripts/build-demo.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
STAFF = ROOT / "site" / "staff"
OUT = STAFF / "app.js"

PARTS = [
    (ROOT / "portal" / "src" / "pricing.js", "pricing engine — copied from portal/src/pricing.js"),
    (STAFF / "demo-data.js", "demo data layer — localStorage, no network"),
    (STAFF / "staff.js", "the screens"),
]


def strip_module_syntax(text: str) -> str:
    """Turn an ES module into plain script body: drop imports, unwrap exports."""
    text = re.sub(r'^\s*import\s[^\n]*?;\s*$', '', text, flags=re.M)
    text = re.sub(r'^export\s+(const|let|var|function|async function|class)\b',
                  r'\1', text, flags=re.M)
    text = re.sub(r'^\s*export\s*\{[^}]*\}\s*;?\s*$', '', text, flags=re.M)
    return text


def main() -> int:
    chunks = [
        "/* GENERATED by portal/scripts/build-demo.py — do not edit.\n"
        "   Edit site/staff/demo-data.js, site/staff/staff.js or portal/src/pricing.js\n"
        "   and re-run the script. One classic script on purpose: a failed ES module\n"
        "   import is silent, and silence is what made this impossible to diagnose. */\n"
        "(function () {\n'use strict';\n"
    ]
    for path, label in PARTS:
        if not path.exists():
            print(f"missing: {path}", file=sys.stderr)
            return 1
        chunks.append(f"\n/* ---------- {label} ---------- */\n")
        chunks.append(strip_module_syntax(path.read_text(encoding="utf-8")))
    chunks.append("\n})();\n")

    OUT.write_text("".join(chunks), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}  ({OUT.stat().st_size // 1024} KB)")

    leftover = [n for n in ("\nimport ", "\nexport ") if n in OUT.read_text(encoding="utf-8")]
    if leftover:
        print(f"  ! module syntax survived: {leftover}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
